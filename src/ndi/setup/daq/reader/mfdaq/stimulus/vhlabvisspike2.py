"""ndi.setup.daq.reader.mfdaq.stimulus.vhlabvisspike2 — VH Lab visual stimulus Spike2 reader.

Device object for the vhlab visual stimulus computer.

This device reads the ``stimtimes.txt``, ``verticalblanking.txt``,
``stims.mat``, and ``spike2data.smr`` files that are present in directories
where a VHLAB stimulus computer (running NewStim/RunExperiment) has produced
triggers that have been acquired on a CED Spike2 system running the VHLAB
Spike2 script.

This device produces the following event channels in each epoch. They are
not read from the CED SMR file but instead are read from the .txt files that
are generated by the vhlab scripts.

=============  ==================================
Channel name   Signal description
=============  ==================================
mk1            stimulus on/off
mk2            stimid
mk3            stimulus open/close (setup/clear)
e1             frame trigger
e2             vertical refresh trigger
e3             pretime trigger
=============  ==================================

MATLAB equivalent: ``+ndi/+setup/+daq/+reader/+mfdaq/+stimulus/vhlabvisspike2.m``

Python-specific Notes:
    ``read_stimtimes_txt`` and ``getstimscript`` are VH Lab library functions;
    they come from ``vhlib.StimDecode`` (vhlab-library-python, a dependency of
    this package), and ``dropnan`` from ``vlt.data`` (vhlab-toolbox-python),
    exactly as MATLAB calls the MATLAB versions. Stimulus parameters are read
    by the companion
    :class:`~ndi.daq.metadatareader.newstim_stims.ndi_daq_metadatareader_NewStimStims`.
"""

from __future__ import annotations

import logging
import os

import numpy as np

from ndi.daq.mfdaq import ChannelInfo, standardize_channel_type
from ndi.daq.reader.mfdaq.cedspike2 import ndi_daq_reader_mfdaq_cedspike2
from ndi.time import DEV_LOCAL_TIME

logger = logging.getLogger(__name__)

STIMTIMES_MAPPING_FILE = "stimtimes2stimtimes_mapping.txt"
MTI_MAPPING_FILE = "mti2stimtimes_mapping.txt"


class VHLabVisSpike2StimulusMismatchError(ValueError):
    """Spike2's stimulus id for a trial does not match the stimulus computer's.

    MATLAB counterpart: ``error('ndi:setup:daq:reader:mfdaq:stimulus:vhlabvisspike2:StimulusMismatch', ...)``
    raised by ``readevents_epochsamples_native``. The identifier is kept on
    the class so a caller can match on it the way MATLAB code matches
    ``ME.identifier``.
    """

    identifier = "ndi:setup:daq:reader:mfdaq:stimulus:vhlabvisspike2:StimulusMismatch"


def _load_mapping(filename: str) -> np.ndarray:
    """MATLAB ``vlt.data.dropnan(load(filename, '-ascii'))`` as 0-based indices."""
    from vlt.data import dropnan

    mapping = np.loadtxt(filename, ndmin=1, dtype=float).ravel()
    # MATLAB indices are 1-based; these index Python lists/arrays.
    return dropnan(mapping).astype(int) - 1


def _mti_list(mti) -> list:
    """The MTI2 cell array as a list (the .mat loader squeezes a 1-entry cell)."""
    if mti is None:
        return []
    if isinstance(mti, np.ndarray):
        return list(mti.ravel())
    if isinstance(mti, (list, tuple)):
        return list(mti)
    return [mti]


def _field(record, name):
    """Read a struct field from a scipy mat_struct, a record, or a dict."""
    if isinstance(record, dict):
        return record[name]
    if isinstance(record, np.void) or (
        isinstance(record, np.ndarray) and record.dtype.names is not None
    ):
        return record[name]
    return getattr(record, name)


class ndi_setup_daq_reader_mfdaq_stimulus_vhlabvisspike2(ndi_daq_reader_mfdaq_cedspike2):
    """VH Lab visual stimulus reader built on CED Spike2.

    The stimulus event channels (``mk1``-``mk3``, ``e1``-``e3``) are decoded
    from ``stimtimes.txt`` and ``stims.mat`` in the epoch directory, aligned
    to Spike2 time; everything else (``t0_t1``) is inherited from the CED
    Spike2 reader.
    """

    NDI_DAQREADER_CLASS = "ndi.setup.daq.reader.mfdaq.stimulus.vhlabvisspike2"

    def epochclock(self, epochfiles: list[str]):
        """Return the clock types for an epoch: a single ``dev_local_time``.

        MATLAB: ``ec = {ndi.time.clocktype('dev_local_time')}``.
        """
        return [DEV_LOCAL_TIME]

    def getchannelsepoch(self, epochfiles: list[str]) -> list[ChannelInfo]:
        """List the channels that are available on this device.

        ============  ==========================
        Channel name  Signal description
        ============  ==========================
        mk1           stimulus on/off
        mk2           stimid
        mk3           stimulus open/close
        e1            frame trigger
        e2            vertical refresh trigger
        e3            pretime trigger
        ============  ==========================
        """
        return [
            ChannelInfo(name="mk1", type="marker", time_channel=None, number=1),
            ChannelInfo(name="mk2", type="marker", time_channel=None, number=2),
            ChannelInfo(name="mk3", type="marker", time_channel=None, number=3),
            ChannelInfo(name="e1", type="event", time_channel=None, number=1),
            ChannelInfo(name="e2", type="event", time_channel=None, number=2),
            ChannelInfo(name="e3", type="event", time_channel=None, number=3),
        ]

    def samplerate(self, epochfiles, channeltype, channel):
        """Get the sample rate for specific channels.

        These are all events, so it doesn't much matter; MATLAB returns
        ``NaN``. Here it is ``NaN`` for each requested channel, as an array,
        the shape every Python ``samplerate`` returns.
        """
        n = 1 if isinstance(channel, (int, np.integer)) else len(channel)
        return np.full(n, np.nan)

    @staticmethod
    def decode_stimulus_records(
        dirname: str,
    ) -> tuple[np.ndarray, np.ndarray, list[np.ndarray], np.ndarray, np.ndarray, np.ndarray]:
        """Align the Spike2 and stimulus-computer records of one epoch directory.

        The decoding half of MATLAB's ``readevents_epochsamples_native``:
        reads ``stimtimes.txt`` (``read_stimtimes_txt``) and ``stims.mat``
        (``getstimscript``), applies ``stimtimes2stimtimes_mapping.txt`` and
        ``mti2stimtimes_mapping.txt`` when present (1-based indices to keep,
        ``NaN`` entries dropped), checks that the two records have the same
        number of triggers and agree on every stimulus id (mod 256), and maps
        the stimulus computer's setup/off/clear times into Spike2 time.

        Returns:
            ``(stimid, stimtimes, frametimes, stimofftimes, stimsetuptimes,
            stimcleartimes)``. ``stimid`` holds the stimulus computer's full
            ids (Spike2 only knows them mod 256).

        Raises:
            ValueError: the trigger counts differ.
            VHLabVisSpike2StimulusMismatchError: a trial's stimulus id differs.
        """
        from vhlib.StimDecode import getstimscript, read_stimtimes_txt

        stimid, stimtimes, frametimes = read_stimtimes_txt(dirname)
        stimid = np.asarray(stimid, dtype=float).ravel()
        stimtimes = np.asarray(stimtimes, dtype=float).ravel()
        frametimes = list(frametimes)

        mappingfile1 = os.path.join(dirname, STIMTIMES_MAPPING_FILE)
        if os.path.isfile(mappingfile1):
            mapping = _load_mapping(mappingfile1)
            stimid = stimid[mapping]
            stimtimes = stimtimes[mapping]
            frametimes = [frametimes[k] for k in mapping]

        _ss, mti = getstimscript(dirname)
        mti = _mti_list(mti)
        mappingfile2 = os.path.join(dirname, MTI_MAPPING_FILE)
        if os.path.isfile(mappingfile2):
            mapping = _load_mapping(mappingfile2)
            mti = [mti[k] for k in mapping]

        if len(mti) != len(stimtimes):
            raise ValueError(
                "Error: The number of stim triggers present in the stimtimes.txt file "
                f"({len(stimtimes)}) differs from what is expected from the content of "
                f"stims.mat file ({len(mti)}) in {dirname}."
            )

        n = len(mti)
        stimofftimes = np.zeros(n)
        stimsetuptimes = np.zeros(n)
        stimcleartimes = np.zeros(n)
        # the epoch directory's name is the vhlab epoch id (e.g. t00006)
        epoch_name = os.path.basename(os.path.normpath(dirname))
        for i in range(n):
            mti_stimid = float(np.asarray(_field(mti[i], "stimid")).ravel()[0])
            if stimid[i] != np.mod(mti_stimid, 256):
                raise VHLabVisSpike2StimulusMismatchError(
                    f"Epoch {epoch_name}: stimulus number {i + 1} does not line up between "
                    "Spike2 and stimulus computer record: "
                    f"Spike2 says {stimid[i]:g} while stimulus computer says {mti_stimid:g} "
                    f"({dirname}). If the two records are offset, a "
                    f"{STIMTIMES_MAPPING_FILE} or {MTI_MAPPING_FILE} file in that directory "
                    "can pair them."
                )
            # needed because now we only know stims on Spike2 up to mod 256
            stimid[i] = mti_stimid
            sst = np.asarray(_field(mti[i], "startStopTimes"), dtype=float).ravel()
            # spike2time = mactime + timeshift
            timeshift = stimtimes[i] - sst[1]
            stimofftimes[i] = sst[2] + timeshift
            stimsetuptimes[i] = sst[0] + timeshift
            stimcleartimes[i] = sst[3] + timeshift

        return stimid, stimtimes, frametimes, stimofftimes, stimsetuptimes, stimcleartimes

    def readevents_epochsamples_native(self, channeltype, channel, epochfiles, t0, t1):
        """Read events or markers of specified channels for a specified epoch.

        ``channeltype`` is a list of channel types (``'event'``, ``'marker'``,
        etc.); a single string applies to all channels. ``channel`` holds the
        (1-based) channel numbers. ``epochfiles`` is the list of file names
        associated with the epoch.

        Returns ``(timestamps, data)``: for markers, ``data`` holds the marker
        code (``mk1``/``mk3``: +1 on, -1 off; ``mk2``: the stimulus id); for
        events it is 1. If more than one channel is requested, each is a list
        with one entry per channel. Only events with ``t0 <= t <= t1`` are
        returned.
        """
        if isinstance(channel, (int, np.integer)):
            channel = [int(channel)]
        if isinstance(channeltype, str):
            channeltype = [channeltype] * len(channel)

        pathnames = [os.path.dirname(f) for f in epochfiles]
        fnames = [os.path.splitext(os.path.basename(f))[0] for f in epochfiles]

        # do the decoding
        (
            stimid,
            stimtimes,
            frametimes,
            stimofftimes,
            stimsetuptimes,
            stimcleartimes,
        ) = self.decode_stimulus_records(pathnames[0])

        def _interleave(on: np.ndarray, off: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
            # alternate on and off times in the final product
            times = np.column_stack([on, off]).ravel()
            codes = np.column_stack([np.ones(len(on)), -np.ones(len(off))]).ravel()
            return times, codes

        timestamps: list[np.ndarray] = []
        data: list[np.ndarray] = []

        for ct, ch in zip(channeltype, channel):
            kind = standardize_channel_type(ct)
            ch = int(ch)
            if kind == "marker":
                if ch == 1:
                    ts, d = _interleave(stimtimes, stimofftimes)
                elif ch == 2:
                    ts, d = stimtimes.copy(), stimid.copy()
                elif ch == 3:
                    ts, d = _interleave(stimsetuptimes, stimcleartimes)
                else:
                    raise ValueError("Unknown channel.")
            elif kind == "event":
                if ch == 1:  # frametimes
                    ts = (
                        np.concatenate([np.asarray(f, dtype=float).ravel() for f in frametimes])
                        if frametimes
                        else np.array([])
                    )
                elif ch == 2:  # vertical refresh
                    vbfile = epochfiles[fnames.index("verticalblanking")]
                    ts = np.loadtxt(vbfile, ndmin=1, dtype=float).ravel()
                elif ch == 3:  # background trigger, simulated
                    ts = stimsetuptimes.copy()
                else:
                    continue
                d = np.ones(len(ts))
            elif kind in ("metadata", "md"):
                continue
            else:
                raise ValueError("Unknown channel.")
            timestamps.append(ts)
            data.append(d)

        for i in range(len(timestamps)):
            keep = (timestamps[i] >= t0) & (timestamps[i] <= t1)
            timestamps[i] = timestamps[i][keep]
            data[i] = data[i][keep]

        # if only 1 channel entry to return, make it non-list
        if len(data) == 1:
            return timestamps[0], data[0]
        return timestamps, data

    def __repr__(self) -> str:
        return f"ndi_setup_daq_reader_mfdaq_stimulus_vhlabvisspike2(id={self.id[:8]}...)"
