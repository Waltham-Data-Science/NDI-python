"""Shared fixtures and configuration for NDI symmetry tests.

Symmetry tests verify cross-language parity between NDI-python and NDI-matlab.
They are separated from the regular test suite because they depend on artifacts
that may have been generated by a prior MATLAB (or Python) run.

See :func:`missing_artifact` for how an absent artifact is handled, which
differs between a local run and CI on purpose.
"""

import os
import tempfile
from pathlib import Path
from typing import NoReturn

import pytest

# Base directory where all symmetry artifacts live:
#   <tempdir>/NDI/symmetryTest/<sourceType>/<namespace>/<class>/<test>/
SYMMETRY_BASE = Path(tempfile.gettempdir()) / "NDI" / "symmetryTest"
PYTHON_ARTIFACTS = SYMMETRY_BASE / "pythonArtifacts"
MATLAB_ARTIFACTS = SYMMETRY_BASE / "matlabArtifacts"

SOURCE_TYPES = ["matlabArtifacts", "pythonArtifacts"]


#: Set by the symmetry workflow's Stage 2. See :func:`missing_artifact`.
STRICT_ENV_VAR = "NDI_SYMMETRY_STRICT"


def strict_mode() -> bool:
    """True when a missing artifact should fail rather than skip."""
    return bool(os.environ.get(STRICT_ENV_VAR))


def missing_artifact(message: str) -> NoReturn:
    """Handle an artifact that is not on disk -- skip locally, FAIL in CI.

    The two cases are genuinely different and want opposite answers:

    - **Locally**, ``matlabArtifacts`` are usually absent, because most
      contributors have no MATLAB. Skipping keeps the suite usable.
    - **In the symmetry workflow**, Stage 1 generates the matlabArtifacts and
      Stage 2's make tests generate the pythonArtifacts before these read
      tests run. Nothing is legitimately absent, so an absent artifact means
      a generator broke -- and a skip would hide it behind a green run.

    That second case is not hypothetical. Four symmetry checks skipped for
    months in exactly this way, over generators that had never been written
    (issue #73); the failure was invisible because a skip is not a failure.
    Issue #77 is the decision to stop letting a check that cannot run report
    the same result as a check that ran and passed.
    """
    if strict_mode():
        pytest.fail(
            f"{message} (strict mode: {STRICT_ENV_VAR} is set, so every artifact "
            "should have been generated by an earlier stage -- a missing one "
            "means a generator broke)"
        )
    pytest.skip(message)
