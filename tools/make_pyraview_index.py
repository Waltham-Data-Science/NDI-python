#!/usr/bin/env python3
"""Regenerate the committed Pyraview wheel index from a GitHub release.

    python tools/make_pyraview_index.py v0.4.2            # rewrite both files
    python tools/make_pyraview_index.py v0.4.2 --check    # exit 1 if stale
    python tools/make_pyraview_index.py v0.4.2 --release-json release.json

Pyraview is not on PyPI. Its wheels -- one per platform and CPython version,
each with the compiled library inside -- are assets on the GitHub release.
This writes two files from that release, both under install/:

``pyraview-wheels.html``
    A flat index (PEP 503 "find-links" page): one ``<a>`` per wheel, its
    ``href`` the release download URL with a ``#sha256=`` fragment. Hand it
    to ``--find-links``, as a local path or by its raw.githubusercontent.com
    URL. The sdist is left OUT on purpose: building Pyraview needs CMake and
    a C++ compiler, and an install that cannot find a wheel must fail rather
    than quietly compile.

``pyraview-constraints.txt``
    ``pyraview==<version>`` with one ``--hash`` per wheel. Passed as
    ``--constraint`` (``uv pip install -c`` / ``uv tool install -c``), it
    makes uv reject any pyraview artifact whose sha256 is not in the list --
    whichever index it came from.

The hashes are the ``digest`` GitHub computes for each release asset, so
nothing is downloaded. ``--release-json`` reads a saved API response instead
of calling the API (for a machine that cannot reach api.github.com).
``GITHUB_TOKEN``, when set, is sent to lift the anonymous rate limit.

``--check`` regenerates in memory and compares with what is committed; CI
runs it so the committed hashes are proved equal to GitHub's own digests.
"""

from __future__ import annotations

import argparse
import html
import json
import os
import sys
import urllib.request
from pathlib import Path

REPO = "VH-Lab/Pyraview"
ROOT = Path(__file__).resolve().parent.parent
INDEX_PATH = ROOT / "install" / "pyraview-wheels.html"
CONSTRAINTS_PATH = ROOT / "install" / "pyraview-constraints.txt"


def fetch_release(tag: str) -> dict:
    """Return the GitHub API description of release TAG."""
    url = f"https://api.github.com/repos/{REPO}/releases/tags/{tag}"
    headers = {"Accept": "application/vnd.github+json"}
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as r:
        return json.load(r)


def wheels(release: dict) -> list[tuple[str, str, str]]:
    """Return (filename, sha256, url) for every wheel asset, sorted by name."""
    out = []
    for asset in release["assets"]:
        name = asset["name"]
        if not name.endswith(".whl"):
            continue  # the sdist, the MATLAB toolbox, the mex files, the zips
        digest = asset.get("digest") or ""
        if not digest.startswith("sha256:"):
            raise SystemExit(f"{name}: release asset has no sha256 digest ({digest!r})")
        out.append((name, digest.removeprefix("sha256:"), asset["browser_download_url"]))
    if not out:
        raise SystemExit(f"release {release.get('tag_name')} has no wheel assets")
    return sorted(out)


def version_of(wheel_list: list[tuple[str, str, str]]) -> str:
    """The single version every wheel in the list carries."""
    versions = {name.split("-")[1] for name, _, _ in wheel_list}
    if len(versions) != 1:
        raise SystemExit(f"wheels carry more than one version: {sorted(versions)}")
    return versions.pop()


def render_index(tag: str, wheel_list: list[tuple[str, str, str]]) -> str:
    lines = [
        "<!DOCTYPE html>",
        "<!-- Generated by tools/make_pyraview_index.py from",
        f"     https://github.com/{REPO}/releases/tag/{tag} -- do not edit by hand.",
        "     Wheels only: the sdist is left out so nothing ever compiles. -->",
        "<html>",
        '<head><meta charset="utf-8"><title>pyraview wheels</title></head>',
        "<body>",
    ]
    for name, sha, url in wheel_list:
        href = html.escape(f"{url}#sha256={sha}", quote=True)
        lines.append(f'<a href="{href}">{html.escape(name)}</a><br>')
    lines += ["</body>", "</html>", ""]
    return "\n".join(lines)


def render_constraints(tag: str, wheel_list: list[tuple[str, str, str]]) -> str:
    version = version_of(wheel_list)
    lines = [
        f"# Generated by tools/make_pyraview_index.py from {REPO} release {tag}.",
        "# Do not edit by hand. One --hash per wheel in install/pyraview-wheels.html;",
        "# passed as --constraint, uv refuses any pyraview file not listed here.",
        f"pyraview=={version} \\",
    ]
    hashes = [f"    --hash=sha256:{sha}" for _, sha, _ in wheel_list]
    lines += [h + " \\" for h in hashes[:-1]] + [hashes[-1], ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("tag", help="release tag, e.g. v0.4.2")
    parser.add_argument("--release-json", type=Path, help="read the API response from a file")
    parser.add_argument("--check", action="store_true", help="fail if the files are stale")
    args = parser.parse_args(argv)

    if args.release_json:
        release = json.loads(args.release_json.read_text())
    else:
        release = fetch_release(args.tag)
    if release.get("tag_name") != args.tag:
        raise SystemExit(f"release JSON is for {release.get('tag_name')!r}, not {args.tag!r}")

    wheel_list = wheels(release)
    wanted = {
        INDEX_PATH: render_index(args.tag, wheel_list),
        CONSTRAINTS_PATH: render_constraints(args.tag, wheel_list),
    }

    if args.check:
        stale = [p for p, text in wanted.items() if not p.exists() or p.read_text() != text]
        for p in stale:
            print(f"STALE: {p.relative_to(ROOT)} does not match release {args.tag}")
        if not stale:
            print(f"OK: {len(wheel_list)} wheels, hashes match GitHub's digests for {args.tag}")
        return 1 if stale else 0

    for p, text in wanted.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    print(f"{len(wheel_list)} wheels from {args.tag}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
